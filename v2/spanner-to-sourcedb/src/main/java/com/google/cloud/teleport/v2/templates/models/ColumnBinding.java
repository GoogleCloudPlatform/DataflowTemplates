package com.google.cloud.teleport.v2.templates.models;

import com.google.common.base.Preconditions;
import com.google.common.collect.ImmutableList;
import java.util.List;
import java.util.Objects;

/**
 * The SQL fragment used for a single column value in a parameterized DML statement, together with
 * the values to be bound to the {@code ?} placeholders in that fragment (in order).
 *
 * <p>The SQL fragment is always generated by the template (for example {@code ?} or {@code
 * CONVERT_TZ(?, '+00:00', ?)}) and never contains user or record data.
 */
public final class ColumnBinding {

  public static final String PLACEHOLDER = "?";

  private final String placeholderSql;
  private final ImmutableList<PreparedStatementValue> params;

  private ColumnBinding(String placeholderSql, List<PreparedStatementValue> params) {
    Preconditions.checkNotNull(placeholderSql, "placeholderSql must not be null");
    Preconditions.checkNotNull(params, "params must not be null");
    long placeholderCount = placeholderSql.chars().filter(c -> c == '?').count();
    Preconditions.checkArgument(
        placeholderCount == params.size(),
        "Placeholder count %s does not match parameter count %s for SQL fragment: %s",
        placeholderCount,
        params.size(),
        placeholderSql);
    this.placeholderSql = placeholderSql;
    this.params = ImmutableList.copyOf(params);
  }

  /** A binding with a single {@code ?} placeholder. */
  public static ColumnBinding of(PreparedStatementValue value) {
    return new ColumnBinding(PLACEHOLDER, ImmutableList.of(value));
  }

  /** A binding with a template-generated SQL fragment containing one {@code ?} per parameter. */
  public static ColumnBinding of(String placeholderSql, List<PreparedStatementValue> params) {
    return new ColumnBinding(placeholderSql, params);
  }

  public String getPlaceholderSql() {
    return placeholderSql;
  }

  public ImmutableList<PreparedStatementValue> getParams() {
    return params;
  }

  @Override
  public boolean equals(Object o) {
    if (this == o) {
      return true;
    }
    if (!(o instanceof ColumnBinding)) {
      return false;
    }
    ColumnBinding that = (ColumnBinding) o;
    return placeholderSql.equals(that.placeholderSql) && params.equals(that.params);
  }

  @Override
  public int hashCode() {
    return Objects.hash(placeholderSql, params);
  }

  @Override
  public String toString() {
    return "ColumnBinding{placeholderSql=" + placeholderSql + ", params=" + params + "}";
  }
}
